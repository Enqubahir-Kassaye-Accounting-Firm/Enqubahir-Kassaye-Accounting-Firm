#!/usr/bin/env node
/**
 * Writes src/config/fonts.ts.
 *   npm run fonts:pin  — load only the body and heading fonts the site uses
 *                        (brand.preset + brand.fonts in site.ts), preloaded.
 *   npm run fonts:all  — load every SUPPORTED_FONTS entry, not preloaded
 *                        (template default; lets any preset be tried).
 * Run fonts:pin again whenever brand.preset or brand.fonts changes.
 * Needs Node ≥ 22.18 (loads the .ts config files directly).
 */

import { writeFileSync } from 'node:fs';
import { SUPPORTED_FONTS, resolveBrand } from '../src/config/presets.ts';
import { siteConfig } from '../src/config/site.ts';

const OUT = new URL('../src/config/fonts.ts', import.meta.url);
const all = process.argv.includes('--all');

const { body, heading } = resolveBrand(siteConfig.brand).fonts;
const fonts = all ? [...SUPPORTED_FONTS] : [...new Set([body, heading])];

for (const font of fonts) {
  if (!SUPPORTED_FONTS.includes(font)) {
    console.error(`"${font}" is not in SUPPORTED_FONTS (src/config/presets.ts).`);
    process.exit(1);
  }
}

/** 'Plus Jakarta Sans' → import Plus_Jakarta_Sans, variable plusJakartaSans */
const importName = (font) => font.replace(/ /g, '_');
const varName = (font) =>
  font
    .split(' ')
    .map((word, i) => (i === 0 ? word.toLowerCase() : word))
    .join('');
const key = (font) => (font.includes(' ') ? `'${font}'` : font);

const header = all
  ? `/**
 * Font loaders for every font in SUPPORTED_FONTS (src/config/presets.ts).
 * next/font needs static calls, so each supported font is declared here once.
 * preload is off because only the two fonts in use are ever downloaded; the
 * browser fetches a font file only when the page actually uses it.
 * Generated by \`npm run fonts:all\`; \`npm run fonts:pin\` loads only this
 * site's fonts (done by /aksumite-template).
 */`
  : `/**
 * Font loaders pinned to this site's fonts (${fonts.join(', ')}), preloaded.
 * Generated by \`npm run fonts:pin\` from brand.preset / brand.fonts in
 * site.ts — run it again after changing them. Other font names fall back to
 * the system font. \`npm run fonts:all\` restores every supported font.
 */`;

const preload = all ? 'false' : 'true';
// Same wrapping Prettier uses at printWidth 100
const names = [...fonts.map(importName), 'Noto_Sans_Ethiopic'].sort();
const oneLineImport = `import { ${names.join(', ')} } from 'next/font/google';`;
const fontImport =
  oneLineImport.length <= 100
    ? oneLineImport
    : `import {\n${names.map((name) => `  ${name},`).join('\n')}\n} from 'next/font/google';`;

// Poppins has no variable version, so next/font needs its weights listed.
const options = (font) =>
  font === 'Poppins'
    ? `{\n  weight: ['400', '500', '600', '700'],\n  subsets: ['latin'],\n  display: 'swap',\n  preload: ${preload},\n}`
    : `{ subsets: ['latin'], display: 'swap', preload: ${preload} }`;

const lines = [
  header,
  '',
  fontImport,
  `import type { FontName } from '@/config/presets';`,
  '',
  ...fonts.map((font) => `const ${varName(font)} = ${importName(font)}(${options(font)});`),
  '',
  '// Amharic letters. The browser downloads this file only for a page that has them.',
  "const notoSansEthiopic = Noto_Sans_Ethiopic({ subsets: ['ethiopic'], display: 'swap', preload: false });",
  'export const ETHIOPIC_FONT = notoSansEthiopic.style.fontFamily;',
  ...(all ? [] : ['', "const systemFont = 'system-ui, sans-serif';"]),
  '',
  'export const FONT_FAMILIES: Record<FontName, string> = {',
  ...SUPPORTED_FONTS.map(
    (font) =>
      `  ${key(font)}: ${fonts.includes(font) ? `${varName(font)}.style.fontFamily` : 'systemFont'},`
  ),
  '};',
  '',
];

writeFileSync(OUT, lines.join('\n'));
console.log(all ? 'fonts.ts: all supported fonts.' : `fonts.ts pinned to: ${fonts.join(', ')}.`);
