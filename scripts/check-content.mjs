#!/usr/bin/env node
/**
 * Content check — catches the mistakes TypeScript cannot see in
 * src/config/site.ts and src/data/*:
 *   - required text that is empty (names, titles, descriptions, quotes, alt text)
 *   - slugs that are not kebab-case or are used twice
 *   - image paths that do not exist in public/
 *   - colors that are not #rgb / #rrggbb
 *   - malformed email, phone (+ and digits), WhatsApp number, Telegram
 *     username, links, and a map URL that is not a Google Maps embed
 *   - homepage section ids listed twice
 *   - hero: a photo layout without alt text
 * Warnings (do not fail): SEO title over 60 or description over 160 characters;
 * a photo hero layout with no photo (the gradient shows); no logo (the name
 * shows as text).
 * Usage: npm run check:content — exits 1 if any problem is found.
 * Needs Node ≥ 22.18 (loads the .ts files directly).
 */

import { existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { z } from 'zod';

import { siteConfig } from '../src/config/site.ts';
import { HOME_PAGE } from '../src/data/home.ts';
import { ABOUT_SUMMARY, ABOUT_PAGE_META } from '../src/data/about.ts';
import { SERVICES, SERVICES_PAGE } from '../src/data/services.ts';
import { PROJECTS, PROJECTS_PAGE } from '../src/data/projects.ts';
import { TESTIMONIALS } from '../src/data/testimonials.ts';
import { PARTNERS } from '../src/data/partners.ts';
import { CONTACT_PAGE } from '../src/data/contact.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

/** Generated by src/app (not files in public/) */
const GENERATED_IMAGES = new Set(['/og-default.png']);

const text = z.string().trim().min(1, 'is empty');
const optional = (schema) => z.union([z.literal(''), schema]);
const slug = z.string().regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/, 'is not kebab-case (e.g. web-design)');
const hex = z.string().regex(/^#(?:[0-9a-f]{3}|[0-9a-f]{6})$/i, 'is not a #rrggbb color');
const url = z.string().url('is not a full link (https://…)');
const email = z.string().email('is not an email address');
const phone = z.string().regex(/^\+[1-9]\d{6,14}$/, "is not '+' and digits, e.g. +251911000000");
const whatsapp = z.string().regex(/^[1-9]\d{6,14}$/, 'must be digits only, without + or spaces');
const telegram = z.string().regex(/^[A-Za-z0-9_]{5,32}$/, 'must be the username only, without @');
const mapEmbed = z
  .string()
  .regex(/^https:\/\/(www\.)?google\.com\/maps\/embed/, 'must be a Google Maps embed URL');
const image = z.object({ url: text, alt: text });

const pageMeta = z.object({ title: text, description: text });

const siteSchema = z.object({
  name: text,
  tagline: text,
  description: text,
  logo: z.string(),
  logoAlt: text,
  logoShape: z.enum(['icon', 'wide']),
  brand: z.object({
    colors: z.record(z.string(), hex),
    surfaces: z
      .object({
        light: z.record(z.string(), hex).optional(),
        dark: z.record(z.string(), hex).optional(),
      })
      .optional(),
  }),
  booking: z.object({ url: optional(url) }),
  contact: z.object({
    email: optional(email),
    phone: optional(phone),
    mapEmbedUrl: optional(mapEmbed),
    people: z.array(
      z.object({
        name: text,
        role: z.string(),
        email: optional(email),
        phone: optional(phone),
        whatsapp: optional(whatsapp),
      })
    ),
  }),
  social: z.object({
    telegram: optional(telegram),
    whatsapp: optional(whatsapp),
    facebook: optional(url),
    instagram: optional(url),
    linkedin: optional(url),
    tiktok: optional(url),
    youtube: optional(url),
    x: optional(url),
  }),
  seo: z.object({
    titleDefault: text,
    titleTemplate: z.string().includes('%s', { message: "must contain '%s'" }),
    metaDescription: text,
    ogTitle: text,
    ogDescription: text,
    ogImage: text,
    ogImageAlt: text,
  }),
  footer: z.object({ description: text, copyrightEntity: text }),
  hero: z.object({
    layout: z.enum(['gradient', 'image', 'split']),
    image: z.object({ url: z.string(), alt: z.string() }),
    imagePosition: text,
    overlay: z.number().min(0).max(1),
    caption: z.string(),
  }),
  credit: z.object({
    name: z.string(),
    url: optional(url),
    email: optional(email),
    instagram: optional(url),
  }),
});

const contentSchemas = [
  ['site.ts', siteSchema, siteConfig],
  ['home.ts', z.object({ heroTitleLines: z.array(text).min(1), heroSubtitle: text }), HOME_PAGE],
  [
    'about.ts',
    z.object({ summary: z.object({ title: text, summary: text }), meta: pageMeta }),
    { summary: ABOUT_SUMMARY, meta: ABOUT_PAGE_META },
  ],
  [
    'services.ts',
    z.object({
      page: z.object({ meta: pageMeta }),
      services: z.array(
        z.object({
          title: text,
          slug,
          description: text,
          fullDescription: text,
          ctaText: text,
          includes: z.array(text),
        })
      ),
    }),
    { page: SERVICES_PAGE, services: SERVICES },
  ],
  [
    'projects.ts',
    z.object({
      page: z.object({ meta: pageMeta }),
      projects: z.array(
        z.object({
          title: text,
          slug,
          summary: text,
          description: text,
          image: image.optional(),
          gallery: z.array(image).optional(),
          url: optional(url).optional(),
        })
      ),
    }),
    { page: PROJECTS_PAGE, projects: PROJECTS },
  ],
  ['testimonials.ts', z.array(z.object({ quote: text, clientName: text })), TESTIMONIALS],
  ['partners.ts', z.array(z.object({ name: text, url: optional(url).optional() })), PARTNERS],
  ['contact.ts', z.object({ title: text, description: text }), CONTACT_PAGE],
];

const problems = [];
const warnings = [];

for (const [file, schema, value] of contentSchemas) {
  const result = schema.safeParse(value);
  if (result.success) continue;
  for (const issue of result.error.issues) {
    problems.push(`${file}: ${issue.path.join('.') || '(root)'} ${issue.message}`);
  }
}

function checkUnique(file, label, values) {
  const seen = new Set();
  for (const value of values) {
    if (seen.has(value)) problems.push(`${file}: ${label} '${value}' is used more than once`);
    seen.add(value);
  }
}

checkUnique(
  'services.ts',
  'slug',
  SERVICES.map((service) => service.slug)
);
checkUnique(
  'projects.ts',
  'slug',
  PROJECTS.map((project) => project.slug)
);
checkUnique('site.ts', 'homeSections id', siteConfig.homeSections);

function checkImage(file, label, path) {
  if (!path || /^https?:\/\//.test(path) || GENERATED_IMAGES.has(path)) return;
  if (!path.startsWith('/')) {
    problems.push(`${file}: ${label} '${path}' must start with / (a path under public/)`);
  } else if (!existsSync(join(ROOT, 'public', decodeURIComponent(path)))) {
    problems.push(`${file}: ${label} '${path}' is not in public/`);
  }
}

checkImage('site.ts', 'logo', siteConfig.logo);
if (!siteConfig.logo) warnings.push('site.ts: logo is empty, so the name shows as text');
checkImage('site.ts', 'logoOnPrimary', siteConfig.logoOnPrimary);
checkImage('site.ts', 'seo.ogImage', siteConfig.seo.ogImage);
checkImage('site.ts', 'hero.image', siteConfig.hero.image.url);
if (siteConfig.hero.layout !== 'gradient') {
  if (!siteConfig.hero.image.url) {
    warnings.push(
      `site.ts: hero.layout is '${siteConfig.hero.layout}' but hero.image.url is empty, so the gradient hero shows`
    );
  } else if (!siteConfig.hero.image.alt.trim()) {
    problems.push('site.ts: hero.image.alt is empty (describe the photo)');
  } else if (/^\/.+\.webp$/.test(siteConfig.hero.image.url)) {
    const small = siteConfig.hero.image.url.replace(/\.webp$/, '-960.webp');
    if (!existsSync(join(ROOT, 'public', decodeURIComponent(small)))) {
      problems.push(`site.ts: hero photo has no ${small} for phones; run npm run images:optimize`);
    }
  }
}
for (const project of PROJECTS) {
  checkImage('projects.ts', `${project.slug} image`, project.image?.url);
  for (const photo of project.gallery ?? []) {
    checkImage('projects.ts', `${project.slug} gallery`, photo.url);
  }
}
for (const partner of PARTNERS) checkImage('partners.ts', `${partner.name} logo`, partner.logo);

if (siteConfig.seo.titleDefault.length > 60) {
  warnings.push(
    `site.ts: seo.titleDefault is ${siteConfig.seo.titleDefault.length} characters (search results show about 60)`
  );
}
if (siteConfig.seo.metaDescription.length > 160) {
  warnings.push(
    `site.ts: seo.metaDescription is ${siteConfig.seo.metaDescription.length} characters (search results show about 160)`
  );
}

for (const warning of warnings) console.log(`warn ${warning}`);
for (const problem of problems) console.log(`FAIL ${problem}`);

if (problems.length > 0) {
  console.error(`\n${problems.length} content problem(s) found.`);
  process.exit(1);
}
console.log('Content check passed.');
